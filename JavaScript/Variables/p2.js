let marks = 85;

if (marks >= 90 && marks <= 100) {
    console.log("A+");
}
else if (marks >= 80) {
    console.log("A");
}
else if (marks >= 70) {
    console.log("B");
}
else if (marks >= 60) {
    console.log("C");
}
else if (marks >= 33) {
    console.log("D");
}
else if (marks >= 0) {
    console.log("Fail");
}
else {
    console.log("Invalid marks");
}